  // ── Current Language（全平台共享偏好）──
  var lang = localStorage.getItem('px_lang') || 'zh';
  I18N.setLang = function (l) {
    lang = l;
    localStorage.setItem('px_lang', l);
    document.documentElement.lang = l;
    document.documentElement.setAttribute('data-lang', l);
    I18N.scan();
    I18N.updateToggles();
    // 通知各模块重渲染动态内容（loader innerHTML）
    try { document.dispatchEvent(new CustomEvent('i18n:changed', { detail: { lang: l } })); } catch (e) {}
  };
  I18N.getLang = function () { return lang; };
  I18N.t = function (key) {
    var tbl = lang === 'zh' ? I18N.zh : I18N.en;
    return (tbl[key] != null) ? tbl[key] : key;
  };

  // ── DOM Scanner（data-i18n / data-i18n-placeholder / data-i18n-title）──
  I18N.scan = function (root) {
    root = root || document.body;
    var tbl = lang === 'zh' ? I18N.zh : I18N.en;
    var els = root.querySelectorAll ? root.querySelectorAll('[data-i18n]') : [];
    for (var i = 0; i < els.length; i++) {
      var el = els[i];
      var key = el.getAttribute('data-i18n');
      if (key && tbl[key] != null) el.textContent = tbl[key];
    }
    els = root.querySelectorAll ? root.querySelectorAll('[data-i18n-placeholder]') : [];
    for (var j = 0; j < els.length; j++) {
      var pk = els[j].getAttribute('data-i18n-placeholder');
      if (pk && tbl[pk] != null) els[j].placeholder = tbl[pk];
    }
    els = root.querySelectorAll ? root.querySelectorAll('[data-i18n-title]') : [];
    for (var k2 = 0; k2 < els.length; k2++) {
      var tk = els[k2].getAttribute('data-i18n-title');
      if (tk && tbl[tk] != null) els[k2].title = tbl[tk];
    }
  };

  // ── 语言切换按钮（.i18n-toggle）──
  I18N.updateToggles = function () {
    var btns = document.querySelectorAll('.i18n-toggle');
    for (var i = 0; i < btns.length; i++) {
      btns[i].textContent = lang === 'zh' ? '\uD83C\uDDEC\uD83C\uDDE7 EN' : '\uD83C\uDDFA\uD83C\uDDF8 \u4E2D\u6587';
    }
  };
  // 供 onclick 使用的切换入口
  I18N.toggle = function () {
    I18N.setLang(I18N.getLang() === 'zh' ? 'en' : 'zh');
  };

  // ── Auto-init ──
  document.addEventListener('DOMContentLoaded', function () {
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
    I18N.scan();
    I18N.updateToggles();
  });
  if (document.readyState !== 'loading') {
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
    I18N.updateToggles();
  }
